export const doualaInput = (value: string | null | undefined) =>
  value ? new Date(new Date(value).getTime() + 3600000).toISOString().slice(0, 16) : '';
export const utcInstant = (value: string) =>
  value ? new Date(value + ':00+01:00').toISOString() : null;
export const displayDate = (value: string, locale: Locale) =>
  new Intl.DateTimeFormat(locale + '-CM', {
    dateStyle: 'medium',
    timeStyle: 'short',
    timeZone: 'Africa/Douala',
  }).format(new Date(value));
