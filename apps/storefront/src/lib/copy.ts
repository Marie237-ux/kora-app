export function money(amount: number | string, locale: Locale): string {
  return (
    new Intl.NumberFormat(locale === 'fr' ? 'fr-FR' : 'en-US', { maximumFractionDigits: 0 })
      .format(Number(amount))
      .replace(/ | /g, ' ') + ' FCFA'
  );
}
export const tones = ['tone-0', 'tone-1', 'tone-2', 'tone-3', 'tone-4', 'tone-5'];
export function tone(key: string): string {
  let h = 0;
  for (const c of key) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  return tones[h % tones.length];
}
